class Translator:
    def __init__(self, lang="ru"):
        self.lang = lang if lang in STRINGS else "ru"

    def __call__(self, key, **kwargs):
        text = STRINGS[self.lang].get(key) or STRINGS["en"].get(key, key)
        return text.format(**kwargs) if kwargs else text
